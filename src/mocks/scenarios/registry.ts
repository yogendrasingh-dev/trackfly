export const DEFAULT_MOCK_SCENARIO_ID: MockScenarioId = "foundation.guest";

export function isMockScenarioId(value: string): value is MockScenarioId {
  return MOCK_SCENARIOS.some((scenario) => scenario.id === value);
}

export function getMockScenario(id: MockScenarioId): MockScenario {
  const scenario = MOCK_SCENARIOS.find((candidate) => candidate.id === id);

  if (!scenario) {
    throw new Error(`Unknown mock scenario: ${id}`);
  }

  return scenario;
}
